"""Tables for the natural-phrasing evaluation in docs/report.md (section 8), from committed outputs only.

    uv run python scripts/natural_tables.py

Reads results/natural/evaluation.json (the one pre-registered run), the GPU reports in
results/natural/kaggle/, the v1 locked-test outputs, and the locked set. Computes nothing new about
any system: GPU systems are restricted to the 238 confirmatory items from their stored item-level
results, with the same family-level bootstrap as ``athar-v2 evaluate``. Writes
results/natural/tables.md.
"""

from __future__ import annotations

import csv
import json
import sys
from collections import Counter
from pathlib import Path

import numpy as np

from athar.data.split import load_split
from athar.eval.stats import mcnemar_exact
from athar.v2.natural import _cfg, _sts_ci, writer_of

ROOT = Path(__file__).resolve().parents[1]
NAT = ROOT / "results" / "natural"
K = NAT / "kaggle"
ROUTES = ("ACT", "CLARIFY", "ABSTAIN")


def load(p: Path) -> dict:
    return json.loads(p.read_text(encoding="utf-8"))


def f3(x: float | None) -> str:
    return "n/a" if x is None else f"{x:.3f}"


def ci(c: dict) -> str:
    return f"[{c['low']:.3f}, {c['high']:.3f}]"


def route_success(items: list[dict]) -> dict[str, float]:
    return {r: float(np.mean([x["success"] for x in items if x["gold_route"] == r])) for r in ROUTES}


def summarize(items: list[dict], fams: list[str], cfg: dict) -> dict:
    s = [float(x["success"]) for x in items]
    executed = [x for x in items if x["executed"]]
    return {"sts": float(np.mean(s)), "ci": _sts_ci(s, fams, cfg),
            "intent_acc": float(np.mean([x["pred_intent"] == x["gold_intent"] for x in items])),
            "unsafe": sum(x["executed"] and not x["success"] for x in items) / len(items),
            "exec_on_non_act": sum(x["executed"] for x in items if x["gold_route"] != "ACT"),
            "executed": len(executed), "invalid": sum(not x["valid"] for x in items),
            "route": route_success(items)}


def main() -> int:
    cfg = _cfg()
    ev = load(NAT / "evaluation.json")
    conf_ids = [x["id"] for x in ev["systems"]["S1"]["items"]]
    conf = set(conf_ids)
    fam_of = {x["id"]: x["family_id"] for x in ev["systems"]["S1"]["items"]}
    out: list[str] = ["# Natural-phrasing evaluation: tables", "",
                      "Generated by `scripts/natural_tables.py` from committed outputs; do not edit by hand.", ""]

    # ---- the set
    items = list(load_split(ROOT / "data/natural/manifest.json", "test", unlock_test=True))
    c_items = [it for it in items if it.id in conf]
    out += ["## Set", "",
            f"- items {len(items)}; confirmatory {len(c_items)} (scenario family in neither train nor dev); "
            f"on training scenarios {len(items) - len(c_items)}",
            f"- writers {len({writer_of(it.id) for it in c_items})}; items per writer "
            f"{min(Counter(writer_of(it.id) for it in c_items).values())}-"
            f"{max(Counter(writer_of(it.id) for it in c_items).values())}",
            f"- families {len({it.family_id for it in c_items})}",
            "- gold route (confirmatory): " + ", ".join(f"{r} {sum(it.route == r for it in c_items)}" for r in ROUTES),
            "- gold intent (confirmatory): " + ", ".join(f"{k} {v}" for k, v in
                                                        Counter(it.intent for it in c_items).most_common()),
            f"- code-switched {sum(bool(it.code_switched) for it in c_items)}; "
            f"project management {sum(it.domain == 'project_management' for it in c_items)}", ""]

    # ---- main table
    rows: list[tuple[str, dict]] = []
    for name in ("oracle-v1.1", "oracle", "S1-v1.1", "S1", "S3-gcv", "S2-gcv", "S3", "S2"):
        it = ev["systems"][name]["items"]
        rows.append((name, summarize(it, [x["family_id"] for x in it], cfg)))
    for base in ("S9", "S8"):
        seeds = [ev["systems"][f"{base}-s{k}"]["items"] for k in range(3)]
        per = [summarize(s, [x["family_id"] for x in s], cfg) for s in seeds]
        mean = ev["summary"][f"{base} (seed mean)"]
        rows.append((f"{base} (3 seeds)", {
            "sts": mean["sts"], "ci": mean["ci"],
            "intent_acc": float(np.mean([p["intent_acc"] for p in per])),
            "unsafe": float(np.mean([p["unsafe"] for p in per])),
            "exec_on_non_act": float(np.mean([p["exec_on_non_act"] for p in per])),
            "invalid": float(np.mean([p["invalid"] for p in per])),
            "route": {r: float(np.mean([p["route"][r] for p in per])) for r in ROUTES},
            "seeds": [p["sts"] for p in per]}))
    gpu = {"S4 Jais-3-3.7B": (K / "2-s4-jais3/s4_results/jais3-3.7b.json", "S4-jais3-3.7b-6shot-prior"),
           "S4 Jais-3-7B": (K / "2-s4-jais3/s4_results/jais3-7b.json", "S4-jais3-7b-6shot-prior"),
           "S4 Jais 2 8B": (K / "3-s4-jais2/s4_results/jais2-8b.json", "S4-jais2-8b-6shot-prior"),
           "S4 Nile-Chat 4B": (K / "4-s4-nile-qwen/s4_results/nile-4b.json", "S4-nile-4b-6shot-prior"),
           "S4 Qwen3 8B": (K / "4-s4-nile-qwen/s4_results/qwen3-8b.json", "S4-qwen3-8b-6shot-prior")}
    gpu_items: dict[str, list[dict]] = {}
    for label, (path, sysname) in gpu.items():
        it = [x for x in load(path)["systems"][sysname]["items"] if x["id"] in conf]
        assert len(it) == len(conf), (label, len(it))
        gpu_items[label] = it
        rows.append((label, summarize(it, [fam_of[x["id"]] for x in it], cfg)))
    s7 = [[x for x in load(K / f"5-s7/s4_results/s7_jais2_qlora_s{k}_test.json")["systems"]
           [f"S7-jais2-qlora-s{k}-prior"]["items"] if x["id"] in conf] for k in range(3)]
    s7sum = [summarize(s, [fam_of[x["id"]] for x in s], cfg) for s in s7]
    s7mean = [float(x) for x in np.mean([[float(x["success"]) for x in s] for s in s7], axis=0)]
    rows.append(("S7 Jais 2 + QLoRA (3 seeds)", {
        "sts": float(np.mean(s7mean)), "ci": _sts_ci(s7mean, [fam_of[i] for i in conf_ids], cfg),
        "intent_acc": float(np.mean([p["intent_acc"] for p in s7sum])),
        "unsafe": float(np.mean([p["unsafe"] for p in s7sum])),
        "exec_on_non_act": float(np.mean([p["exec_on_non_act"] for p in s7sum])),
        "invalid": 0.0, "route": {r: float(np.mean([p["route"][r] for p in s7sum])) for r in ROUTES},
        "seeds": [p["sts"] for p in s7sum]}))
    out += ["## Main results (238 confirmatory items)", "",
            "| System | STS [95% CI] | Intent acc. | Unsafe exec. | Executed non-ACT | ACT / CLARIFY / ABSTAIN success | Invalid |",
            "|---|---|---|---|---|---|---|"]
    for name, r in sorted(rows, key=lambda t: -t[1]["sts"]):
        seeds = f" (seeds {' / '.join(f3(x) for x in r['seeds'])})" if "seeds" in r else ""
        out.append(f"| {name} | {f3(r['sts'])} {ci(r['ci'])}{seeds} | {f3(r['intent_acc'])} | {f3(r['unsafe'])} | "
                   f"{r['exec_on_non_act']:g} | {' / '.join(f3(r['route'][x]) for x in ROUTES)} | {r['invalid']:g} |")
    out.append("")

    # ---- hypotheses
    out += ["## Pre-registered hypotheses (Holm over N1-N3)", "",
            "| | Difference [95% CI] | p | Holm p | Writer-clustered p | McNemar (only A / only B) |",
            "|---|---|---|---|---|---|"]
    wcl = ev["sensitivity"]["writer_clustered"]
    for h, t in ev["tests"].items():
        mc = t.get("mcnemar")
        mcs = f"{mc['only_a']} / {mc['only_b']} (p {mc['p_value']:.2g})" if mc else "n/a (seed means)"
        out.append(f"| {h} | {t['difference']:+.3f} [{t['ci']['low']:+.3f}, {t['ci']['high']:+.3f}] | "
                   f"{t['p_value']:.4f} | {t['p_holm']:.4f} | {wcl[h]['p_value']:.4f} | {mcs} |")
    lowo = ev["sensitivity"]["leave_one_writer_out"]
    out += ["", "Leave-one-writer-out STS range (17 analyses):", ""]
    for n in ("S1", "S1-v1.1", "S2", "S8 (seed mean)", "S9 (seed mean)"):
        v = [w[n] for w in lowo.values()]
        out.append(f"- {n}: {min(v):.3f}-{max(v):.3f}")
    keep = all(w["S1"] > w["S2"] and w["S9 (seed mean)"] > w["S8 (seed mean)"] for w in lowo.values())
    out += [f"- S1 > S2 and S9 > S8 in every leave-one-writer-out analysis: {keep}", ""]

    # ---- per writer
    per_w: dict[str, list[float]] = {}
    for n in ("S1", "S2"):
        for x in ev["systems"][n]["items"]:
            per_w.setdefault(writer_of(x["id"]), [])
    s8m = np.mean([[x["success"] for x in ev["systems"][f"S8-s{k}"]["items"]] for k in range(3)], axis=0)
    s9m = np.mean([[x["success"] for x in ev["systems"][f"S9-s{k}"]["items"]] for k in range(3)], axis=0)
    out += ["## Per writer (descriptive)", "", "| Writer | n | S1 | S2 | S8 (seed mean) | S9 (seed mean) |",
            "|---|---|---|---|---|---|"]
    ids = conf_ids
    by_w: dict[str, list[int]] = {}
    for k, i in enumerate(ids):
        by_w.setdefault(writer_of(i), []).append(k)
    s1 = [x["success"] for x in ev["systems"]["S1"]["items"]]
    s2 = [x["success"] for x in ev["systems"]["S2"]["items"]]
    for w in sorted(by_w, key=lambda w: -len(by_w[w])):
        ks = by_w[w]
        out.append(f"| {w.upper()} | {len(ks)} | {np.mean([s1[k] for k in ks]):.2f} | {np.mean([s2[k] for k in ks]):.2f} | "
                   f"{np.mean(s8m[ks]):.2f} | {np.mean(s9m[ks]):.2f} |")
    wins = sum(np.mean([s1[k] for k in ks]) > np.mean([s2[k] for k in ks]) for ks in by_w.values())
    wins9 = sum(np.mean(s9m[ks]) > np.mean(s8m[ks]) for ks in by_w.values())
    out += ["", f"S1 > S2 for {wins} of {len(by_w)} writers; S9 > S8 for {wins9} of {len(by_w)}.", ""]

    # ---- v1 locked test vs natural
    v1 = load(ROOT / "results/test_results.json")["systems"]
    v1_gpu = {}
    for f in ("7a-jais3", "7b-others"):
        for r in csv.DictReader(open(ROOT / f"results/s4/{f}/s4_results/summary.csv", encoding="utf-8")):
            v1_gpu[r["system"]] = float(r["STS"])
    v1_s7 = [float(r["STS"]) for r in csv.DictReader(open(ROOT / "results/s4/7cd-s7-s8/s4_results/s7_seeds.csv",
                                                          encoding="utf-8"))
             if r["split"] == "test" and r["system"].endswith("-prior")]
    v1_s8 = load(ROOT / "results/s4/7cd-s7-s8/s4_results/s8_jais3-7b.json")["systems"]
    v1_s8_sts = [v1_s8[f"S8-jais3-7b-s{k}"]["metrics"]["safe_task_success"] for k in range(3)]
    v1_s8_route = {r: float(np.mean([v1_s8[f"S8-jais3-7b-s{k}"]["metrics"]["success_by_gold_route"][r]
                                     for k in range(3)])) for r in ROUTES}
    nat = dict(rows)
    pairs = [("oracle", v1["oracle"]["metrics"]["safe_task_success"], nat["oracle"]["sts"]),
             ("S1", v1["S1"]["metrics"]["safe_task_success"], nat["S1"]["sts"]),
             ("S3", v1["S3"]["metrics"]["safe_task_success"], nat["S3"]["sts"]),
             ("S2", v1["S2"]["metrics"]["safe_task_success"], nat["S2"]["sts"]),
             ("S7 (3 seeds)", float(np.mean(v1_s7)), nat["S7 Jais 2 + QLoRA (3 seeds)"]["sts"]),
             ("S8 (3 seeds)", float(np.mean(v1_s8_sts)), nat["S8 (3 seeds)"]["sts"])]
    for label, key in (("S4 Jais 2 8B", "jais2-8b"), ("S4 Jais-3-3.7B", "jais3-3.7b"), ("S4 Nile-Chat 4B", "nile-4b"),
                       ("S4 Qwen3 8B", "qwen3-8b"), ("S4 Jais-3-7B", "jais3-7b")):
        pairs.append((label, v1_gpu[f"S4-{key}-6shot-prior"], nat[label.replace("S4 Jais 2 8B", "S4 Jais 2 8B")]["sts"]))
    out += ["## v1 locked test (author, 120) vs natural set (contributors, 238), descriptive", "",
            "Different items, writers and route mixes (v1: 50/50/20 ACT/CLARIFY/ABSTAIN): not a paired comparison.", "",
            "| System | v1 test STS | Natural STS | Change |", "|---|---|---|---|"]
    for name, a, b in pairs:
        out.append(f"| {name} | {a:.3f} | {b:.3f} | {b - a:+.3f} |")
    s8n = nat["S8 (3 seeds)"]["route"]
    oracle_v1_route = v1["oracle"]["metrics"]["success_by_gold_route"]
    out += ["", "Success by gold route:", "", "| System | v1 ACT / CLARIFY / ABSTAIN | Natural ACT / CLARIFY / ABSTAIN |",
            "|---|---|---|",
            f"| oracle | {' / '.join(f3(oracle_v1_route[r]) for r in ROUTES)} | {' / '.join(f3(nat['oracle']['route'][r]) for r in ROUTES)} |",
            f"| S8 (seed mean) | {' / '.join(f3(v1_s8_route[r]) for r in ROUTES)} | {' / '.join(f3(s8n[r]) for r in ROUTES)} |",
            f"| S9 (seed mean) | n/a | {' / '.join(f3(nat['S9 (3 seeds)']['route'][r]) for r in ROUTES)} |", ""]

    # ---- author vs contributor on shared slots
    avc = ev["author_vs_contributor"]
    out += ["## Same scenario slots: author's locked test items vs contributors' items (descriptive)", "",
            f"{avc['slots']} (card, version) slots written by both; {avc['contributor_items']} contributor items on them. "
            "Contributor STS is averaged per slot. The v1.1 systems were changed after the v1 error analysis of "
            "exactly these author items, so their author column is not a held-out score.", "",
            "| System | Author items | Contributor items | Gap |", "|---|---|---|---|"]
    for n, v in avc["systems"].items():
        out.append(f"| {n} | {v['author']:.3f} | {v['contributors']:.3f} | {v['contributors'] - v['author']:+.3f} |")
    out.append("")

    # ---- S9 vs S8 decomposition
    s8 = [ev["systems"][f"S8-s{k}"]["items"] for k in range(3)]
    s9 = [ev["systems"][f"S9-s{k}"]["items"] for k in range(3)]
    gain = [sum(b["success"] and not a["success"] for a, b in zip(x, y, strict=True)) for x, y in zip(s8, s9, strict=True)]
    loss = [sum(a["success"] and not b["success"] for a, b in zip(x, y, strict=True)) for x, y in zip(s8, s9, strict=True)]
    gain_r = {r: [sum(b["success"] and not a["success"] for a, b in zip(x, y, strict=True) if a["gold_route"] == r)
                  for x, y in zip(s8, s9, strict=True)] for r in ROUTES}
    loss_r = {r: [sum(a["success"] and not b["success"] for a, b in zip(x, y, strict=True) if a["gold_route"] == r)
                  for x, y in zip(s8, s9, strict=True)] for r in ROUTES}
    inv = [sum(not a["valid"] for a in x) for x in s8]
    inv_fixed = [sum((not a["valid"]) and b["success"] for a, b in zip(x, y, strict=True)) for x, y in zip(s8, s9, strict=True)]
    out += ["## S9 vs S8, per seed (item level)", "",
            f"- items S9 gets right and S8 wrong: {gain}; the reverse: {loss}",
            *[f"- {r}: S9 only {gain_r[r]}, S8 only {loss_r[r]}" for r in ROUTES],
            f"- S8 answers without a valid tool call: {inv}; of these, S9 gets right: {inv_fixed}", ""]

    # ---- inline vs turns on 238 (descriptive)
    out += ["## S4 exemplar format on the confirmatory items (descriptive; not among N1-N3)", "",
            "| Model | Inline | Chat turns | Only inline / only turns right | Exact McNemar p |", "|---|---|---|---|---|"]
    for label, (path, sysname) in gpu.items():
        rep = load(path)["systems"]
        t = [x["success"] for x in rep[sysname]["items"] if x["id"] in conf]
        i = [x["success"] for x in rep[sysname.replace("6shot-prior", "6shot-inline-prior")]["items"] if x["id"] in conf]
        m = mcnemar_exact(i, t)
        out.append(f"| {label.replace('S4 ', '')} | {np.mean(i):.3f} | {np.mean(t):.3f} | {m['only_a']} / {m['only_b']} | {m['p_value']:.3f} |")
    out.append("")

    # ---- S4/S7 with core v1.1
    L = ev["llm_with_core_v1.1"]
    out += ["## S4 / S7 rebuilt with core v1.1 from their stored intents (descriptive)", "",
            "`stored` = the GPU run's own score on these items; `rebuilt_v1` = the same intents through the frozen v1 "
            "core on CPU (a reproduction check); `with_core_v1.1` = through core v1.1.", "",
            "| System | stored | rebuilt v1 | with core v1.1 |", "|---|---|---|---|"]
    for n, v in L.items():
        if n.endswith("6shot-prior") or (n.startswith("S7") and n.endswith("-prior")):
            out.append(f"| {n} | {v['stored']:.3f} | {v['rebuilt_v1']:.3f} | {v['with_core_v1.1']:.3f} |")
    same = all(v["stored"] == v["rebuilt_v1"] for v in L.values())
    out += ["", f"All {len(L)} stored GPU scores reproduced exactly by the CPU rebuild: {same}", ""]

    # ---- training scenarios
    out += ["## Items on training scenarios (descriptive, 9 items)", "",
            ", ".join(f"{k} {v:.3f}" for k, v in ev["training_scenarios"].items()), ""]
    (NAT / "tables.md").write_text("\n".join(out), encoding="utf-8", newline="\n")
    print("wrote", (NAT / "tables.md").relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
