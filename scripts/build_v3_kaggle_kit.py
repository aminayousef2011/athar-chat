"""Package protocol v3's S6 run (MARBERTv2, gates G2+G3) for a Kaggle GPU: dist/athar-v3-kit.zip.

    uv run python scripts/build_v3_kaggle_kit.py

Upload the zip as a **private** Kaggle Dataset named ``athar-v3-kit``, attach it to a new GPU
notebook (T4 is enough; internet on to download MARBERTv2 at its pinned revision) and run one cell:

    !cp -r /kaggle/input/athar-v3-kit/* /kaggle/working/ && cd /kaggle/working && python kaggle_v3_s6.py

It writes ``/kaggle/working/v3_s6_outputs.zip`` (``models_v3/freeze_s6.json``, the S6 prediction
files and ``environment.json``). Unzip it into the repository root, then run
``uv run python -m athar.v3 verify`` and commit.

Unlike dist/athar-chat-kit (an installed wheel), this kit ships the source tree: the v3 freeze
hashes the source files and finds its data relative to them. Private data, minimised: the 236 v3
texts (the model must read them) and, with their text columns blanked, the v3 collection and the
blocks' kept files (only card ids, versions and writer codes are used there).
"""

from __future__ import annotations

import csv
import shutil
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
KIT = ROOT / "dist" / "athar-v3-kit"
PRIVATE = ROOT / "data" / "raw" / "private"
FILES = [
    "configs/train.yaml", "configs/eval.yaml",
    "data/athar.jsonl", "data/splits/manifest.json",
    "data/natural/natural.jsonl", "data/natural/manifest.json", "data/natural/sample.json",
    "docs/protocol_v3.md", "models_v2/freeze.json",
]

RUNNER = '''"""Kaggle runner for protocol v3 S6 (generated by scripts/build_v3_kaggle_kit.py)."""
import json, platform, subprocess, sys, zipfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "src"))
import torch, transformers  # noqa: E402

from athar.v3.__main__ import main  # noqa: E402

device = "cuda" if torch.cuda.is_available() else "cpu"
print("device:", device, torch.cuda.get_device_name(0) if device == "cuda" else "")
env = {"python": platform.python_version(), "torch": torch.__version__, "transformers": transformers.__version__,
       "device": device, "gpu": torch.cuda.get_device_name(0) if device == "cuda" else None}
assert main(["verify"]) == 0, "the S3 freeze in this kit does not verify: rebuild the kit"
rc = main(["freeze-s6", "--device", device])
Path("environment.json").write_text(json.dumps(env, indent=1), encoding="utf-8")
with zipfile.ZipFile("v3_s6_outputs.zip", "w", zipfile.ZIP_DEFLATED) as z:
    z.write("models_v3/freeze_s6.json")
    z.write("environment.json", "results/v3/environment_s6.json")
    for f in sorted(Path("results/v3/predictions").glob("S6-*.json")):
        z.write(f)
print("exit", rc, "-> /kaggle/working/v3_s6_outputs.zip")
'''


def _strip_text(src: Path, dst: Path) -> int:
    with src.open(encoding="utf-8-sig", newline="") as f:
        rows = list(csv.DictReader(f))
    dst.parent.mkdir(parents=True, exist_ok=True)
    with dst.open("w", encoding="utf-8-sig", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        for r in rows:
            w.writerow({**r, "text": "", "comment": ""})
    return len(rows)


def main() -> int:
    if KIT.exists():
        shutil.rmtree(KIT)
    KIT.mkdir(parents=True)
    shutil.copytree(ROOT / "src" / "athar", KIT / "src" / "athar",
                    ignore=shutil.ignore_patterns("__pycache__", "*.pyc"))
    shutil.copytree(ROOT / "models_v3", KIT / "models_v3")
    shutil.copytree(ROOT / "results" / "v3", KIT / "results" / "v3")
    for rel in FILES:
        (KIT / rel).parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / rel, KIT / rel)
    v3 = PRIVATE / "v3"
    (KIT / "data/raw/private/v3").mkdir(parents=True)
    shutil.copy2(v3 / "v3_unlabelled.csv", KIT / "data/raw/private/v3/v3_unlabelled.csv")
    _strip_text(v3 / "v3_collection.csv", KIT / "data/raw/private/v3/v3_collection.csv")
    kept = 0
    for f in sorted((PRIVATE / "contrib").glob("*/*_kept.csv")):
        kept += _strip_text(f, KIT / f.relative_to(ROOT))
    (KIT / "kaggle_v3_s6.py").write_text(RUNNER, encoding="utf-8")
    archive = ROOT / "dist" / "athar-v3-kit.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as z:
        for f in sorted(KIT.rglob("*")):
            if f.is_file():
                z.write(f, f.relative_to(KIT).as_posix())
    print(f"wrote {archive.relative_to(ROOT)} ({archive.stat().st_size / 1024:.0f} KB); "
          f"v3 texts: 236 messages; kept files with text blanked: {kept} rows")
    return 0


if __name__ == "__main__":
    sys.exit(main())
