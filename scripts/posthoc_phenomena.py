"""Post hoc (2026-11-05): Safe Task Success by Egyptian-Arabic phenomenon on the natural set.

Tags each of the 238 confirmatory contributor messages with surface phenomena by regular
expression on the raw text (a heuristic tagger; tags overlap), then reads each system's stored
per-item success from the locked evaluation (results/natural/evaluation.json and the S4 GPU
report). Nothing is re-run. Descriptive only: no tests, and small cells are marked.

    uv run python scripts/posthoc_phenomena.py      # -> results/posthoc/phenomena.{json,md}
"""

from __future__ import annotations

import json
import re
import sys
from collections.abc import Callable
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "results" / "posthoc"

AR = "؀-ۿ"
PHENOMENA: dict[str, Callable[[str], bool]] = {
    "code-switched (Latin script)": lambda t: bool(re.search(r"[A-Za-z]", t)),
    "English time/period token (am, pm, meeting, deadline…)": lambda t: bool(
        re.search(r"(?i)\b(am|pm|a\.m|p\.m|morning|tonight|tomorrow|today|deadline|meeting|call)\b", t)),
    "Arabic-Indic digits (٠-٩)": lambda t: bool(re.search(r"[٠-٩]", t)),
    "no digits (hour in words or none)": lambda t: not re.search(r"[0-9٠-٩]", t),
    "spelled-out hour or fraction (ونص، وربع، الا ربع، تلاتة…)": lambda t: bool(re.search(
        rf"(?<![{AR}])(ونص|و نص|وربع|و ربع|الا ربع|إلا ربع|الا تلت|وتلت|واحده|واحدة|اتنين|تلاته|تلاتة|اربعه|اربعة|خمسه|خمسة|سته|ستة|سبعه|سبعة|تمانيه|تمانية|تسعه|تسعة|عشره|عشرة|حداشر|اتناشر)(?![{AR}])", t)),
    "verb trigger (فكرني، ذكرني، صحيني، نبهني)": lambda t: bool(re.search(r"(فكر|ذكر|صحي|نبه)ني|فكرنى|ذكرنى", t)),
    "tool noun request (تذكير، منبه، alarm, reminder)": lambda t: bool(
        re.search(r"(?i)تذكير|منبه|منبّه|alarm|reminder", t)),
    "want-verb (عايز، عاوز، محتاج)": lambda t: bool(re.search(r"عايز|عاوز|محتاج", t)),
    "politeness (لو سمحت، من فضلك، please)": lambda t: bool(re.search(r"(?i)لو سمحت|من فضلك|please|plz|لو ينفع", t)),
    "relative time (بعد ساعة، بعد شوية، كمان…)": lambda t: bool(re.search(r"بعد\s*(ساعه|ساعة|ساعتين|نص|ربع|شويه|شوية|دقايق|\d)|كمان\s", t)),
    "day-scale expression (بعد اسبوع، الجاي، اللي جاي)": lambda t: bool(re.search(r"الجاي|الجايه|الجاية|اللي جاي|بعد اسبوع|بعد شهر|بعد بكره|بعد بكرة", t)),
    "letter elongation (e.g. ااا)": lambda t: bool(re.search(rf"([{AR}])\1\1", t)),
    "long message (> 12 words)": lambda t: len(t.split()) > 12,
}


def main() -> int:
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    ev = json.loads((REPO / "results/natural/evaluation.json").read_text(encoding="utf-8"))
    texts = {json.loads(line)["id"]: json.loads(line)["text"]
             for line in (REPO / "data/natural/natural.jsonl").read_text(encoding="utf-8").splitlines() if line.strip()}
    succ: dict[str, dict[str, float]] = {}
    for name in ("oracle", "S1", "S2"):
        succ[name] = {x["id"]: float(x["success"]) for x in ev["systems"][name]["items"]}
    for prefix in ("S8", "S9"):
        seeds = [{x["id"]: float(x["success"]) for x in ev["systems"][f"{prefix}-s{s}"]["items"]} for s in range(3)]
        succ[f"{prefix} (3 seeds)"] = {i: float(np.mean([sd[i] for sd in seeds])) for i in seeds[0]}
    s4 = json.loads((REPO / "results/natural/kaggle/2-s4-jais3/s4_results/jais3-3.7b.json").read_text(encoding="utf-8"))
    rep = s4["systems"]["S4-jais3-3.7b-6shot-prior"]["items"]
    conf_ids = set(succ["S1"])
    succ["S4 Jais-3-3.7B"] = {x["id"]: float(x["success"]) for x in rep if x["id"] in conf_ids}
    ids = sorted(conf_ids)
    systems = list(succ)
    rows = []
    for label, test in [("all confirmatory items", lambda t: True), *PHENOMENA.items()]:
        sel = [i for i in ids if test(texts[i])]
        row = {"phenomenon": label, "n": len(sel)}
        for s in systems:
            row[s] = round(float(np.mean([succ[s][i] for i in sel])), 3) if sel else None
        rows.append(row)
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "phenomena.json").write_text(json.dumps(rows, ensure_ascii=False, indent=1), encoding="utf-8")
    head = "| Phenomenon | n | " + " | ".join(systems) + " |"
    lines = ["# STS by phenomenon (natural set, 238 confirmatory items; post hoc, descriptive)", "",
             "Generated by `scripts/posthoc_phenomena.py`. Tags are heuristic regular expressions and overlap. "
             "Cells with n < 20 are in italics.", "", head, "|" + "---|" * (len(systems) + 2)]
    for r in rows:
        cells = [("" if r[s] is None else (f"*{r[s]:.3f}*" if r["n"] < 20 else f"{r[s]:.3f}")) for s in systems]
        lines.append(f"| {r['phenomenon']} | {r['n']} | " + " | ".join(cells) + " |")
    (OUT / "phenomena.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
