"""Dataset statistics as Markdown, written into the data card between fixed markers."""

from __future__ import annotations

import statistics
from collections import Counter
from collections.abc import Callable, Sequence
from pathlib import Path

from athar.schema import INTENTS, ROUTES, GoldItem
from athar.timeexpr import GAP_ORDER

START, END = "<!-- stats:start -->", "<!-- stats:end -->"
SOURCES = ("author", "contributor", "assistant_draft")
REASONS = ("deletion", "modification", "recurring", "other_person", "multi_action", "other_tool", "other")


def _eq(field: str, value: object) -> Callable[[GoldItem], bool]:
    return lambda it: bool(getattr(it, field) == value)


def _has_target(gap: str) -> Callable[[GoldItem], bool]:
    return lambda it: gap in it.clarify_targets


def _table(columns: dict[str, Sequence[GoldItem]],
           rows: Sequence[tuple[str, Callable[[GoldItem], bool]]]) -> list[str]:
    head = "| | " + " | ".join(columns) + " |"
    out = [head, "|---" * (len(columns) + 1) + "|"]
    for label, pred in rows:
        out.append(f"| {label} | " + " | ".join(str(sum(map(pred, items))) for items in columns.values()) + " |")
    return out


def stats_markdown(items: Sequence[GoldItem], splits: dict[str, Sequence[GoldItem]] | None = None,
                   title: str = "") -> str:
    columns: dict[str, Sequence[GoldItem]] = {"all": items, **(splits or {})}
    fams = Counter(it.family_id for it in items)
    pairs = {it.pair_id for it in items if it.pair_id}
    lengths = [len(it.text.split()) for it in items]
    lines = [f"Generated by `athar-data stats` from {title}." if title else "Generated by `athar-data stats`.", ""]
    lines.append(f"{len(items)} items in {len(fams)} families "
                 f"(family size {min(fams.values(), default=0)}-{max(fams.values(), default=0)}), "
                 f"{len(pairs)} complete/incomplete pairs; request length "
                 f"{min(lengths, default=0)}-{max(lengths, default=0)} words "
                 f"(median {statistics.median(lengths) if lengths else 0:g}).")
    lines.append("")
    rows: list[tuple[str, Callable[[GoldItem], bool]]] = []
    rows += [(f"route {r}", _eq("route", r)) for r in ROUTES]
    rows += [(f"intent {i}", _eq("intent", i)) for i in INTENTS]
    rows += [(f"target `{g}`", _has_target(g)) for g in GAP_ORDER]
    rows += [(f"reason {r}", _eq("unsupported_reason", r)) for r in REASONS]
    rows += [("code-switched", _eq("code_switched", True))]
    rows += [(f"source {s}", _eq("source", s)) for s in SOURCES]
    rows += [("**items**", lambda it: True)]
    lines += _table(columns, rows)
    return "\n".join(lines) + "\n"


def write_into_card(card: str | Path, block: str) -> None:
    p = Path(card)
    text = p.read_text(encoding="utf-8")
    if START not in text or END not in text:
        raise ValueError(f"{card} has no {START} ... {END} block")
    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    p.write_text(f"{head}{START}\n{block}{END}{tail}", encoding="utf-8", newline="\n")
